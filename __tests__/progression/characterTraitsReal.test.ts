const ROOT = path.resolve(__dirname, '..', '..');
const code = (rel: string) =>
  fs.readFileSync(path.join(ROOT, rel), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:])\/\/.*$/gm, '$1');

function startFrom(scenarioId: string): GameState {
  const scenario = scenarios.find((s) => s.id === scenarioId);
  if (!scenario) throw new Error(scenarioId);
  // The real builder over the real template - the path a new life takes.
  const built: GameState = buildNewGameState({
    initialGameState,
    stateVersion: 54,
    firstName: 'Test',
    lastName: 'Player',
    sex: 'male',
    sexuality: 'straight',
    scenario: { ...scenario },
    selectedPerks: [],
    permanentPerks: [],
    selectedMindset: null,
  });
  return built;
}

const deps = {
  updateMoney,
  updateStats,
  gainCriminalXp: jest.fn(),
  gainCrimeSkillXp: jest.fn(),
};

function job(state: GameState, id: string): StreetJob {
  return state.streetJobs.find((j) => j.id === id)!;
}

describe('every scenario trait does something', () => {
  const used = [...new Set(scenarios.flatMap((s) => s.start.traits ?? []))];

  it.each(used)('%s has a real effect and panel copy', (id) => {
    const effect = SCENARIO_TRAIT_EFFECTS[id];
    expect(effect).toBeDefined();
    expect(Object.keys(effect.start ?? {}).length + Object.keys(effect.street ?? {}).length).toBeGreaterThan(0);
    expect(describeScenarioTrait(id).length).toBeGreaterThan(0);
  });
});

describe('start effects are applied by the builder', () => {
  const baseFitness = initialGameState.stats.fitness;

  it('Fit: Fitness Enthusiast starts 20 fitness higher', () => {
    expect(startFrom('fitness_enthusiast').stats.fitness).toBe(baseFitness + 20);
    expect(startFrom('highschool_dropout').stats.fitness).toBe(baseFitness);
  });

  it('Criminal Record: Second Chance starts at criminal level 2, which the hiring check reads', () => {
    const s = startFrom('second_chance');
    expect(s.criminalLevel).toBe(2);
    // One level above the clean baseline of 1.
    expect(hiringPenalty(s.criminalLevel, s.wantedLevel)).toBe(5);
    expect(hiringPenalty(initialGameState.criminalLevel, 0)).toBe(0);
    expect(startFrom('highschool_dropout').criminalLevel).toBe(initialGameState.criminalLevel);
  });

  it('Smart: Tech Prodigy starts with Hacking at level 2 (+5% on hacking jobs)', () => {
    const s = startFrom('tech_prodigy');
    expect(s.crimeSkills.hacking.level).toBe(2);
    expect(s.crimeSkills.stealth.level).toBe(1);
    const plain = startFrom('highschool_dropout');
    const hack = 'hack_public_wifi';
    expect(getStreetJobTerms(s, job(s, hack)).successChance - getStreetJobTerms(plain, job(plain, hack)).successChance).toBe(5);
  });

  it("Caring: the Single Parent's child starts 15 bond higher, in BOTH lists", () => {
    const s = startFrom('single_parent_life');
    const child = s.family.children[0];
    expect(child.relationshipScore).toBe(Math.min(100, NEWBORN_BOND + 15));
    expect(s.relationships.find((r) => r.id === child.id)?.relationshipScore).toBe(child.relationshipScore);
  });

  it('the builder records the traits the life holds', () => {
    expect(heldScenarioTraits(startFrom('second_chance').activeTraits).sort()).toEqual(['criminal_record', 'tough']);
  });
});

describe('street effects are read from the traits this life holds', () => {
  const withTraits = (activeTraits: string[]) =>
    createTestGameState({ activeTraits, stats: { money: 1_000, energy: 100, health: 80, happiness: 80 } });

  it('Tough: street jobs cost 1 less health', () => {
    const plain = withTraits([]);
    const tough = withTraits(['tough']);
    expect(getStreetJobTerms(tough, job(tough, 'wash_cars')).healthCost)
      .toBe(getStreetJobTerms(plain, job(plain, 'wash_cars')).healthCost + 1);
  });

  it('Disciplined: street jobs cost 1 less happiness', () => {
    const plain = withTraits([]);
    const disc = withTraits(['disciplined']);
    expect(getStreetJobTerms(disc, job(disc, 'wash_cars')).happinessCost)
      .toBe(getStreetJobTerms(plain, job(plain, 'wash_cars')).happinessCost + 1);
  });

  it('Determined: the next street job is guaranteed after 3 straight failures, not 5', () => {
    expect(PITY_THRESHOLD_STREET_JOB).toBe(5);
    const setter = (() => undefined) as unknown as Dispatch<SetStateAction<GameState>>;
    // Dumpster diving succeeds 20% of the time; with 3 failures banked a
    // Determined life cannot fail, on any seed.
    for (let w = 100; w < 140; w++) {
      const s = createTestGameState({
        weeksLived: w,
        activeTraits: ['determined'],
        stats: { money: 0, energy: 100, health: 100, happiness: 100 },
        weeklyStreetJobs: {},
        streetJobFailureCount: { dumpster: 3 },
      });
      expect(performStreetJob(s, setter, 'dumpster', deps).success).toBe(true);
    }
  });

  it('an heir does not keep the founder’s traits: the panel reads activeTraits, not scenarioId', () => {
    const heir = createTestGameState({ scenarioId: 'second_chance', activeTraits: [] });
    expect(traitPanelEntries({ activeTraits: heir.activeTraits, stats: { happiness: 50, health: 50, energy: 50 } })).toEqual([]);
  });
});

describe('stat traits describe what the game does with the stat', () => {
  const ALL: StatTraitId[] = ['happy', 'sad', 'healthy', 'sick', 'energetic', 'tired'];
  const VITALS: Record<StatTraitId, { happiness: number; health: number; energy: number }> = {
    happy: { happiness: 85, health: 50, energy: 50 },
    sad: { happiness: 10, health: 50, energy: 50 },
    healthy: { happiness: 50, health: 90, energy: 50 },
    sick: { happiness: 50, health: 20, energy: 50 },
    energetic: { happiness: 50, health: 50, energy: 90 },
    tired: { happiness: 50, health: 50, energy: 10 },
  };

  it.each(ALL)('%s claims no salary bonus, energy grant or immunity', (id) => {
    const lines = describeStatTrait(id, VITALS[id]).join(' | ');
    expect(lines).not.toMatch(/salary|immun|energy per week|per week|bonus action|reputation/i);
    expect(deriveStatTraits(VITALS[id])).toContain(id);
  });

  it('the job-performance number is calculatePerformance, not a restated weight', () => {
    const lines = describeStatTrait('energetic', VITALS.energetic).join(' ');
    const expected = calculatePerformance({ energy: 90, happiness: 50, health: 50 }) - calculatePerformance({ energy: 50, happiness: 50, health: 50 });
    expect(lines).toContain(`Job performance +${expected} from energy`);
  });

  it('faster healing is only claimed where the tick grants it (health ABOVE 70)', () => {
    expect(describeStatTrait('healthy', { health: 70 }).join(' ')).not.toMatch(/heal faster/);
    expect(describeStatTrait('healthy', { health: 71 }).join(' ')).toMatch(/heal faster/);
  });

  it('the thresholds it quotes are the ones the systems use', () => {
    const disease = code('lib/diseases/diseaseGenerator.ts');
    expect(disease).toMatch(new RegExp(`health < ${ILLNESS_RISK_HEALTH_FLOOR}\\)`));
    expect(disease).toMatch(/riskMultiplier \+= healthPenalty \* 2\.0;/); // "up to 3x" at 0
    const recovery = code('contexts/game/actions/weekly/applyDiseases.ts');
    expect(recovery).toMatch(new RegExp(`ctx\\.newStats\\.health > ${FAST_RECOVERY_HEALTH_ABOVE}\\) \\{\\s*recoveryDecrement \\+= 0\\.5;`));
  });
});

describe('IdentityCard renders the derived lines, not a hand-written table', () => {
  const card = code('components/IdentityCard.tsx');

  it('builds the panel from traitPanelEntries over activeTraits', () => {
    expect(card).toMatch(/traitPanelEntries\(\{ activeTraits: gameState\.activeTraits, stats \}\)/);
    expect(card).toMatch(/activeTraits: s\?\.activeTraits/);
  });

  it('the invented bonus table is gone', () => {
    expect(card).not.toMatch(/getTraitBonuses/);
    expect(card).not.toMatch(/Immunity to sickness/);
    expect(card).not.toMatch(/salary bonus/);
    expect(card).not.toMatch(/scenario\?\.start\.traits/);
  });
});

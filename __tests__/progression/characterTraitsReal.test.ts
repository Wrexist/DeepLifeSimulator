/**
 * The Home "Traits" panel only claims what the game does - 2026-10-17 owner
 * call.
 *
 * At health >= 70 it promised "+15% salary bonus, +8 energy per week, Immunity
 * to sickness": `careerPayMultiplier` has no stat term, nothing grants weekly
 * energy, and illness rolls at any health. The scenario traits it listed (fit,
 * smart, criminal_record, ...) were written to `activeTraits` by the builder
 * and read by nothing. Now:
 *   - scenario traits have real effects through systems that already exist,
 *     applied by the builder (start) or by `getStreetJobTerms` (street work);
 *   - every panel line is generated by `lib/mindset/characterTraits.ts` from
 *     the same numbers and functions the game applies.
 */

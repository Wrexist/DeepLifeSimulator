// Deterministic crops of reviewed imagegen sheets; no runtime network dependency.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const sharp = require('../art/game-assets-v1/source/node_modules/sharp');
const root = path.resolve(__dirname, '..');
const families = {
  pets: {
    ids: ['dog','dog_golden','dog_poodle','cat','cat_tabby','cat_black','bird','bird_parrot','bird_canary','fish','fish_tropical','fish_puffer','hamster','hamster_mouse','hamster_hedgehog','rabbit','rabbit_lop','turtle','turtle_tortoise'],
    x: [0,280,561,842,1122], y: [0,281,563,823,1103,1402],
  },
  travel: {
    ids: ['local_resort','paris','tokyo','bali','new_york','swiss_alps','london','dubai','rome','thailand','sydney','cancun','iceland','safari','maldives','camping_trip','road_trip'],
    x: [0,267,560,854,1122], y: [0,280,562,826,1110,1402],
  },
  vehicles: {
    ids: ['economy_sedan','compact_hatchback','used_suv','family_suv','sedan_premium','luxury_sedan','luxury_suv','supercar_entry','exotic_supercar','sports_coupe','muscle_car','standard_motorcycle','sport_motorcycle','cruiser_motorcycle','utility_helicopter','light_jet'],
    x: [0,313,627,941,1254], y: [0,305,610,920,1202],
  },
};
const hash = buffer => crypto.createHash('sha256').update(buffer).digest('hex');
(async () => {
  const assets = [];
  const maps = [];
  for (const [family, { ids, x, y }] of Object.entries(families)) {
    const source = `art/life-family-v1/originals/${family}.png`;
    const original = fs.readFileSync(path.join(root, source));
    const entries = [];
    for (const [index, id] of ids.entries()) {
      const col = index % 4, row = Math.floor(index / 4);
      let crop = { left: x[col] + 2, top: y[row] + 2, width: x[col + 1] - x[col] - 4, height: y[row + 1] - y[row] - 4 };
      const override = id === 'utility_helicopter' ? fs.readFileSync(path.join(root, 'art/life-family-v1/originals/utility_helicopter.png')) : null;
      if (override) crop = { left:0, top:0, width:1254, height:1254 };
      const file = `assets/images/life-family-v1/${family}/${id}.webp`;
      const target = path.join(root, file);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      await sharp(override || original).extract(crop).resize(256,256,{ fit:'contain', background:'#102334' }).flatten({ background:'#102334' }).webp({ quality:86 }).toFile(target);
      const output = fs.readFileSync(target);
      assets.push({ family,id,source:override ? 'art/life-family-v1/originals/utility_helicopter.png' : source,crop,file,width:256,height:256,bytes:output.length,sha256:hash(output),sourceSha256:hash(override || original) });
      entries.push(`  '${id}': require('@/${file}'),`);
    }
    maps.push(`export const ${family.toUpperCase()}_ART: Record<string, ImageSourcePropType> = {\n${entries.join('\n')}\n};`);
  }
  fs.writeFileSync(path.join(root,'lib/content/lifeArtAssets.ts'), "// Generated by scripts/normalize-life-art.cjs; stable catalogue IDs, local assets only.\nimport type { ImageSourcePropType } from 'react-native';\n\n" + maps.join('\n\n') + '\n');
  fs.writeFileSync(path.join(root,'art/life-family-v1/manifest.json'), JSON.stringify({ tool:'built-in image_gen', review:'Reviewed sheet order and individual runtime crops. Native rendering acceptance remains open.', assets },null,2)+'\n');
  console.log({ assets:assets.length, bytes:assets.reduce((sum,a)=>sum+a.bytes,0) });
})().catch(error => { console.error(error); process.exit(1); });

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const sharp = require('../art/game-assets-v1/source/node_modules/sharp');
const root = path.resolve(__dirname, '..');
const sheets = {
  collectibles: ['rare_watch_collection', 'museum_diamond', 'fine_art_collection', 'supercar'],
  'estates-transport': ['racehorse', 'vineyard_estate', 'luxury_yacht', 'private_jet'],
  landmarks: ['private_island', 'trophy_penthouse', 'mega_yacht', 'sports_team_stake'],
};
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
(async () => {
  const assets = [], entries = [];
  for (const [sheet, ids] of Object.entries(sheets)) {
    const source = `art/luxury-v2/originals/${sheet}.png`;
    const original = fs.readFileSync(path.join(root, source));
    const meta = await sharp(original).metadata();
    for (const [index, id] of ids.entries()) {
      const col = index % 2, row = Math.floor(index / 2);
      const left = Math.floor(meta.width * col / 2), top = Math.floor(meta.height * row / 2);
      const crop = { left, top, width: Math.floor(meta.width * (col + 1) / 2) - left, height: Math.floor(meta.height * (row + 1) / 2) - top };
      const file = `assets/images/luxury-v2/${id}.webp`, target = path.join(root, file);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      await sharp(original).extract(crop).resize(768,384,{ fit:'contain', background:'#102334' }).flatten({ background:'#102334' }).webp({ quality:86 }).toFile(target);
      const output = fs.readFileSync(target);
      assets.push({ id,source,crop,file,width:768,height:384,bytes:output.length,sha256:hash(output),sourceSha256:hash(original) });
      entries.push(`  '${id}': require('@/${file}'),`);
    }
  }
  fs.writeFileSync(path.join(root,'lib/content/luxuryArtAssets.ts'), "// Generated by scripts/normalize-luxury-art.cjs; immutable catalogue IDs.\nimport type { ImageSourcePropType } from 'react-native';\n\nexport const LUXURY_ART: Record<string, ImageSourcePropType> = {\n"+entries.join('\n')+'\n};\n');
  fs.writeFileSync(path.join(root,'art/luxury-v2/manifest.json'),JSON.stringify({ tool:'built-in image_gen',review:'All twelve source subjects reviewed for category identity, framing and shared lighting. Native image acceptance remains open.',assets },null,2)+'\n');
  console.log({ assets:assets.length,bytes:assets.reduce((n,a)=>n+a.bytes,0) });
})().catch(error=>{ console.error(error);process.exit(1); });

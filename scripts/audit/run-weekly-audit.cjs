#!/usr/bin/env node
/**
 * Weekly Audit Orchestrator — DeepLife Simulator
 *
 * Runs all five routine audits, prints a console summary, and writes a single timestamped
 * Markdown report to tasks/weekly-audit-<YYYY-MM-DD>.md. Designed to run unattended in CI
 * every Monday as a Claude Routine (Code → Routines) and on demand via `npm run audit:weekly`.
 *
 * Exit code:
 *   0  no critical/high findings (warnings allowed)
 *   1  at least one critical or high finding (CI fails, issue opened)
 *
 * Flags:
 *   --run-tests   also execute the performance jest suite (dynamic timing)
 *   --no-report   print only, don't write the Markdown file
 *   --quiet       suppress passing lines in console output (AUDIT_QUIET=1)
 */
'use strict';

const fs = require('fs');
const path = require('path');
const L = require('./_lib.cjs');

const MODULES = [
  require('./audit-economy.cjs'),
  require('./audit-stability.cjs'),
  require('./audit-save.cjs'),
  require('./audit-logic.cjs'),
  require('./audit-perf.cjs'),
];

function main() {
  const args = process.argv.slice(2);
  const runTests = args.includes('--run-tests');
  const writeReport = !args.includes('--no-report');
  if (args.includes('--quiet')) process.env.AUDIT_QUIET = '1';

  console.log(L.c.bold(L.c.magenta('\n╔══════════════════════════════════════════════╗')));
  console.log(L.c.bold(L.c.magenta('║   DeepLife Simulator — Weekly Routine Audit    ║')));
  console.log(L.c.bold(L.c.magenta('╚══════════════════════════════════════════════╝')));

  const audits = [];
  for (const mod of MODULES) {
    // audit-perf accepts an options object; others ignore extra args.
    const audit = mod.build({ runTests });
    L.printConsole(audit);
    audits.push(audit);
  }

  // --- aggregate ----------------------------------------------------------
  const totals = { critical: 0, high: 0, medium: 0, low: 0, pass: 0, info: 0 };
  for (const a of audits) for (const lvl of Object.keys(totals)) totals[lvl] += a.count(lvl);
  const blockers = totals.critical + totals.high;

  console.log('');
  console.log(L.c.bold('────────────────────────────────────────────────'));
  console.log(L.c.bold(' Aggregate'));
  for (const a of audits) {
    const tag = a.failed ? L.c.red('FAIL') : (a.count('medium') + a.count('low') ? L.c.yellow('WARN') : L.c.green('OK  '));
    console.log(`  [${tag}] ${a.id}. ${a.title}  ${L.c.gray(`(🔴${a.count('critical')} 🟠${a.count('high')} 🟡${a.count('medium')} ⚪${a.count('low')} ✅${a.count('pass')})`)}`);
  }
  console.log(L.c.bold('────────────────────────────────────────────────'));

  // --- report -------------------------------------------------------------
  if (writeReport) {
    const reportPath = writeMarkdown(audits, totals, blockers);
    console.log(L.c.gray(`\n📄 Report: ${path.relative(L.REPO_ROOT, reportPath)}`));
  }

  if (blockers > 0) {
    console.log(L.c.red(L.c.bold(`\n✗ Weekly audit FAILED — ${totals.critical} critical, ${totals.high} high. See report.`)));
    process.exit(1);
  }
  const warns = totals.medium + totals.low;
  console.log(warns
    ? L.c.yellow(`\n⚠ Weekly audit passed with ${warns} warning(s) — review the report.`)
    : L.c.green(L.c.bold('\n✓ Weekly audit clean — all invariants green.')));
  process.exit(0);
}

function writeMarkdown(audits, totals, blockers) {
  const date = new Date().toISOString().slice(0, 10);
  const verdict = blockers > 0
    ? `🔴 **FAIL** — ${totals.critical} critical, ${totals.high} high`
    : (totals.medium + totals.low
      ? `🟡 **PASS (warnings)** — ${totals.medium} medium, ${totals.low} low`
      : '🟢 **CLEAN** — all invariants green');

  const lines = [];
  lines.push(`# DeepLife Simulator — Weekly Routine Audit (${date})`);
  lines.push('');
  lines.push('Generated by `npm run audit:weekly` (`scripts/audit/run-weekly-audit.cjs`). Deterministic');
  lines.push('static analysis of the five routine domains. Severity: 🔴 critical · 🟠 high · 🟡 medium · ⚪ low.');
  lines.push('');
  lines.push(`**Verdict:** ${verdict}`);
  lines.push('');
  lines.push('| # | Domain | 🔴 | 🟠 | 🟡 | ⚪ | ✅ |');
  lines.push('|---|--------|----|----|----|----|----|');
  for (const a of audits) {
    lines.push(`| ${a.id} | ${a.title} | ${a.count('critical')} | ${a.count('high')} | ${a.count('medium')} | ${a.count('low')} | ${a.count('pass')} |`);
  }
  lines.push('');
  lines.push('---');
  lines.push('');
  for (const a of audits) lines.push(L.toMarkdown(a));
  lines.push('---');
  lines.push('');
  lines.push('_Generated by the weekly Claude Routine. Re-run locally with `npm run audit:weekly`._');
  lines.push('');

  const out = path.join(L.REPO_ROOT, 'tasks', `weekly-audit-${date}.md`);
  fs.writeFileSync(out, lines.join('\n'), 'utf8');
  return out;
}

main();
